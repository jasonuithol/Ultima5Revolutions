#!/usr/bin/env python3
"""Generate rust/src/g.rs: named DGROUP offset constants from analysis/symbols.json."""
import json, os, re
R = os.path.expanduser('~/Projects/Ultima5Revolutions')
sym = json.load(open(f'{R}/analysis/symbols.json'))
globs = sym['globals']
lines = ['//! DGROUP global offsets (generated by tools/gen_globals.py from analysis/symbols.json; do not edit).',
         '//! Offsets are relative to DS=0x1f64 (DATA.OVL file offset minus 0x10). Access through Game/Mem helpers.',
         '#![allow(dead_code, non_upper_case_globals)]', '']
seen = set()
for off in sorted(globs, key=lambda o: int(o, 16)):
    g = globs[off]
    name = re.sub(r'^g_', '', g['name']).upper()
    name = re.sub(r'[^A-Z0-9_]', '_', name)
    if name[0].isdigit(): name = 'G_' + name
    if name in seen: name = f"{name}_{off[2:]}"
    seen.add(name)
    meaning = (g.get('meaning') or '').replace('\n', ' ')
    typ = g.get('type') or '?'
    lines.append(f"/// {typ}: {meaning}")
    lines.append(f"pub const {name}: u16 = {off};")
open(f'{R}/rust/src/g.rs', 'w').write('\n'.join(lines) + '\n')
print('wrote', len(seen), 'constants')
